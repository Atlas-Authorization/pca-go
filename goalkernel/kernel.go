//go:build pcagoalkernel

// Package goalkernel runs the Dafny-proved goal compiler (formal/dafny/Goal.dfy: typecheck, compile, the reference decision D_G,
// the compiled policy's decision with its witness, and the lossless card tape) through its Go translation in internal/gen,
// produced with the pinned Dafny by formal/dafny/build-native.sh go. There is no decision logic here: callers pass and receive
// token tapes (the same tapes as @atlasauth/pca-verified-core goalCall), and no Dafny value crosses this boundary.
//
// The package builds only with the build tag pcagoalkernel, because internal/gen is generated by CI (see internal/gen/README.md).
package goalkernel

import (
	"errors"
	"fmt"
	"strconv"
	"strings"

	GoalApi "github.com/Atlas-Authorization/pca-go/goalkernel/internal/gen/GoalApi"
	GoalRender "github.com/Atlas-Authorization/pca-go/goalkernel/internal/gen/GoalRender"
	_dafny "github.com/Atlas-Authorization/pca-go/goalkernel/internal/gen/dafny"
)

// Tok is one tape token: Tag 'k' (keyword, Int), 'i' (integer, Int) or 's' (string, Str).
type Tok struct {
	Tag byte
	Int int64
	Str string
}

// Tape is a token tape.
type Tape []Tok

// K, I and S build tokens.
func K(n int64) Tok  { return Tok{Tag: 'k', Int: n} }
func I(n int64) Tok  { return Tok{Tag: 'i', Int: n} }
func S(s string) Tok { return Tok{Tag: 's', Str: s} }

// ErrRejected is returned when the kernel refuses an input tape (first output token i9) or its output is malformed.
var ErrRejected = errors.New("pca-goal: compiler rejected the input tape")

const maxSafe = 9007199254740991

var api = GoalApi.Companion_Default___

func toDafny(t Tape) (_dafny.Sequence, error) {
	xs := make([]interface{}, 0, len(t))
	for _, x := range t {
		switch x.Tag {
		case 'k', 'i':
			if x.Int > maxSafe || x.Int < -maxSafe {
				return nil, fmt.Errorf("pca-goal: goal tape: %d is not a safe integer", x.Int)
			}
			if x.Tag == 'k' {
				xs = append(xs, api.MkKw(_dafny.IntOfInt64(x.Int)))
			} else {
				xs = append(xs, api.MkI(_dafny.IntOfInt64(x.Int)))
			}
		case 's':
			cps := make([]interface{}, 0, len(x.Str))
			for _, r := range x.Str {
				cps = append(cps, _dafny.CodePoint(r))
			}
			xs = append(xs, api.MkS(_dafny.SeqOf(cps...)))
		default:
			return nil, fmt.Errorf("pca-goal: goal tape: unknown token tag %q", x.Tag)
		}
	}
	return _dafny.SeqOf(xs...), nil
}

func intOf(n _dafny.Int) (int64, error) {
	v, err := strconv.ParseInt(n.String(), 10, 64)
	if err != nil {
		return 0, fmt.Errorf("pca-goal: kernel integer out of range: %w", err)
	}
	return v, nil
}

func fromDafny(s _dafny.Sequence) (Tape, error) {
	n := s.Cardinality()
	out := make(Tape, 0, n)
	for i := uint32(0); i < n; i++ {
		t, ok := s.Select(i).(GoalRender.Tok)
		if !ok {
			return nil, ErrRejected
		}
		kind, err := intOf(api.TokKind(t))
		if err != nil {
			return nil, err
		}
		switch kind {
		case 0, 1:
			f := api.TokKw
			if kind == 1 {
				f = api.TokInt
			}
			v, err := intOf(f(t))
			if err != nil {
				return nil, err
			}
			out = append(out, Tok{Tag: "ki"[kind], Int: v})
		default:
			str := api.TokStr(t)
			var b strings.Builder
			for j := uint32(0); j < str.Cardinality(); j++ {
				cp, ok := str.Select(j).(_dafny.CodePoint)
				if !ok {
					return nil, ErrRejected
				}
				b.WriteRune(rune(cp))
			}
			out = append(out, S(b.String()))
		}
	}
	return out, nil
}

// Call runs one proved entry point: op in typecheck, compile, decideg, decidep, render (act and hist are used by the decide ops).
// First output token: i0 ok, i1 rejected with reasons, i9 malformed input. A panic inside the translation is returned as an error.
func Call(op string, goal, ont, act, hist Tape) (out Tape, err error) {
	defer func() {
		if r := recover(); r != nil {
			out, err = nil, fmt.Errorf("pca-goal: goal kernel failed: %v", r)
		}
	}()
	g, err := toDafny(goal)
	if err != nil {
		return nil, err
	}
	o, err := toDafny(ont)
	if err != nil {
		return nil, err
	}
	switch op {
	case "typecheck":
		return fromDafny(api.TypecheckT(g, o))
	case "compile":
		return fromDafny(api.CompileT(g, o))
	case "render":
		return fromDafny(api.RenderT(g))
	case "decideg", "decidep":
		a, err := toDafny(act)
		if err != nil {
			return nil, err
		}
		h, err := toDafny(hist)
		if err != nil {
			return nil, err
		}
		if op == "decideg" {
			return fromDafny(api.DecideGoalT(g, o, a, h))
		}
		return fromDafny(api.DecidePolicyT(g, o, a, h))
	}
	return nil, fmt.Errorf("pca-goal: goal kernel: unknown op %q", op)
}

// ---- the typed front door (compiler.ts), over tapes ----

func first(t Tape) (int64, error) {
	if len(t) == 0 || t[0].Tag != 'i' {
		return 0, ErrRejected
	}
	return t[0].Int, nil
}

func reasons(t Tape) ([]string, error) {
	if len(t) < 2 || t[1].Tag != 'i' || t[1].Int < 0 || int64(len(t)-2) < t[1].Int {
		return nil, ErrRejected
	}
	out := []string{}
	for _, x := range t[2 : 2+t[1].Int] {
		out = append(out, x.Str)
	}
	return out, nil
}

func decision(n int64) string {
	switch n {
	case 2:
		return "allow"
	case 1:
		return "escalate"
	}
	return "deny"
}

// Typecheck returns the type reasons of a goal against an ontology; empty = well typed.
func Typecheck(goal, ont Tape) ([]string, error) {
	out, err := Call("typecheck", goal, ont, nil, nil)
	if err != nil {
		return nil, err
	}
	switch s, err := first(out); {
	case err != nil:
		return nil, err
	case s == 0:
		return []string{}, nil
	case s == 1:
		return reasons(out)
	}
	return nil, ErrRejected
}

// CompileResult is C(goal): OK with the policy tape, or the escalation reasons.
type CompileResult struct {
	OK      bool
	Policy  Tape
	Reasons []string
}

// CompileGoal compiles a goal; ill-typed goals are rejected, never coerced.
func CompileGoal(goal, ont Tape) (CompileResult, error) {
	out, err := Call("compile", goal, ont, nil, nil)
	if err != nil {
		return CompileResult{}, err
	}
	switch s, err := first(out); {
	case err != nil:
		return CompileResult{}, err
	case s == 0:
		return CompileResult{OK: true, Policy: out[1:]}, nil
	case s == 1:
		rs, err := reasons(out)
		return CompileResult{Reasons: rs}, err
	}
	return CompileResult{}, ErrRejected
}

// DecideGoal is the reference semantics D_G(a, H): "allow", "escalate" or "deny".
func DecideGoal(goal, ont, act, hist Tape) (string, error) {
	out, err := Call("decideg", goal, ont, act, hist)
	if err != nil {
		return "", err
	}
	if s, err := first(out); err != nil || s != 0 || len(out) < 2 || out[1].Tag != 'i' {
		return "", ErrRejected
	}
	return decision(out[1].Int), nil
}

// Witness names the grant and bounds behind an Allow.
type Witness struct {
	Gid  string
	Bids []string
}

// PolicyDecision is the compiled policy's decision, the witness of an Allow (nil otherwise) and the checker's verdict on it.
// OK is false (with Reasons) when the goal does not compile.
type PolicyDecision struct {
	OK             bool
	Reasons        []string
	Decision       string
	Witness        *Witness
	WitnessChecked bool
}

// DecidePolicy decides with the compiled policy.
func DecidePolicy(goal, ont, act, hist Tape) (PolicyDecision, error) {
	out, err := Call("decidep", goal, ont, act, hist)
	if err != nil {
		return PolicyDecision{}, err
	}
	s, err := first(out)
	if err != nil {
		return PolicyDecision{}, err
	}
	if s == 1 {
		rs, err := reasons(out)
		return PolicyDecision{Reasons: rs}, err
	}
	if s != 0 || len(out) < 4 || out[1].Tag != 'i' || out[3].Tag != 'i' || out[3].Int < 0 || int64(len(out)) < 5+out[3].Int {
		return PolicyDecision{}, ErrRejected
	}
	n := out[3].Int
	d := PolicyDecision{OK: true, Decision: decision(out[1].Int), WitnessChecked: out[4+n].Int == 1}
	if d.Decision == "allow" {
		w := &Witness{Gid: out[2].Str, Bids: []string{}}
		for _, x := range out[4 : 4+n] {
			w.Bids = append(w.Bids, x.Str)
		}
		d.Witness = w
	}
	return d, nil
}

// RenderTape is the card as a token tape (GoalRender.Render): parsing it gives the goal back.
func RenderTape(goal Tape) (Tape, error) {
	out, err := Call("render", goal, nil, nil, nil)
	if err != nil {
		return nil, err
	}
	if s, err := first(out); err != nil || s != 0 {
		return nil, ErrRejected
	}
	return out[1:], nil
}

// ---- harness text syntax (kN, iN, s<hex>.<hex>...) ----

// TapeToText renders a tape in the differential-harness syntax.
func TapeToText(t Tape) string {
	parts := make([]string, 0, len(t))
	for _, x := range t {
		if x.Tag == 's' {
			hs := []string{}
			for _, r := range x.Str {
				hs = append(hs, strconv.FormatInt(int64(r), 16))
			}
			parts = append(parts, "s"+strings.Join(hs, "."))
		} else {
			parts = append(parts, string(x.Tag)+strconv.FormatInt(x.Int, 10))
		}
	}
	return strings.Join(parts, " ")
}

// TapeFromText parses the differential-harness syntax.
func TapeFromText(s string) (Tape, error) {
	out := Tape{}
	for _, x := range strings.Split(s, " ") {
		if x == "" {
			continue
		}
		b := x[1:]
		switch x[0] {
		case 'k', 'i':
			n, err := strconv.ParseInt(b, 10, 64)
			if err != nil {
				return nil, fmt.Errorf("pca-goal: tape text: %q: %w", x, err)
			}
			out = append(out, Tok{Tag: x[0], Int: n})
		case 's':
			var sb strings.Builder
			if b != "" {
				for _, h := range strings.Split(b, ".") {
					r, err := strconv.ParseInt(h, 16, 32)
					if err != nil {
						return nil, fmt.Errorf("pca-goal: tape text: %q: %w", x, err)
					}
					sb.WriteRune(rune(r))
				}
			}
			out = append(out, S(sb.String()))
		default:
			return nil, fmt.Errorf("pca-goal: tape text: bad token %q", x)
		}
	}
	return out, nil
}
