func k05HexBytes(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(strings.Join(strings.Fields(s), ""))
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// k05HugeVector returns the oversized public key and the signature padded to the modulus length.
func k05HugeVector(t *testing.T, nHex, sHex string) (*rsa.PublicKey, []byte) {
	t.Helper()
	pk := &rsa.PublicKey{N: new(big.Int).SetBytes(k05HexBytes(t, nHex)), E: 3}
	if pk.N.BitLen() != 16385 {
		t.Fatalf("vector modulus has %d bits, want 16385", pk.N.BitLen())
	}
	if rsaKeyOK(pk) {
		t.Fatal("a 16385-bit modulus must not pass the usable-key rule")
	}
	s := k05HexBytes(t, sHex)
	sig := make([]byte, (pk.N.BitLen()+7)/8)
	copy(sig[len(sig)-len(s):], s)
	return pk, sig
}

func TestK05JwsRS256RefusesAnOversizedModulusWhoseSignatureVerifies(t *testing.T) {
	pk, sig := k05HugeVector(t, k05HugeN1, k05HugeS1)
	input := []byte("eyJhbGciOiJSUzI1NiJ9.eyJzdWIiOiJ4In0")
	sum := sha256.Sum256(input)
	if err := rsa.VerifyPKCS1v15(pk, crypto.SHA256, sum[:], sig); err != nil {
		t.Fatalf("the vector must be a genuine signature under the oversized key: %v", err)
	}
	if jwsRS256OK(sig, input, certKey{pub: pk}) {
		t.Fatal("an RS256 signature verified under a modulus over 16384 bits")
	}
}

// pssParams is RSASSA-PSS-params with SHA-256, MGF1 over SHA-256, salt length 32 and trailer field 1.
func k05PssParamsSHA256Salt32() []byte {
	sha := []byte{0x30, 0x0d, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x02, 0x01, 0x05, 0x00}
	mgf := append([]byte{0x30, 0x1a, 0x06, 0x09, 0x2a, 0x86, 0x48, 0x86, 0xf7, 0x0d, 0x01, 0x01, 0x08}, sha...)
	var body []byte
	body = append(body, append([]byte{0xa0, byte(len(sha))}, sha...)...)
	body = append(body, append([]byte{0xa1, byte(len(mgf))}, mgf...)...)
	body = append(body, 0xa2, 0x03, 0x02, 0x01, 0x20, 0xa3, 0x03, 0x02, 0x01, 0x01)
	return append([]byte{0x30, byte(len(body))}, body...)
}

func TestK05CertSigRsaPssRefusesAnOversizedModulusWhoseSignatureVerifies(t *testing.T) {
	pk, sig := k05HugeVector(t, k05HugeN2, k05HugeS2)
	tbs := []byte("tbs-bytes-signed-by-the-issuer")
	sum := sha256.Sum256(tbs)
	if err := rsa.VerifyPSS(pk, crypto.SHA256, sum[:], sig, &rsa.PSSOptions{SaltLength: 32}); err != nil {
		t.Fatalf("the vector must be a genuine PSS signature under the oversized key: %v", err)
	}
	params := k05PssParamsSHA256Salt32()
	if h, mgf, salt, ok := pssParamsRaw(params); !ok || h != crypto.SHA256 || mgf != crypto.SHA256 || salt != 32 {
		t.Fatalf("pss parameters parse to %v %v %d %v", h, mgf, salt, ok)
	}
	child := &attCert{RawTBS: tbs, SigOID: "1.2.840.113549.1.1.10", SigParams: params, Signature: sig}
	if certSigOK(child, certKey{pub: pk}) {
		t.Fatal("a certificate signature verified under a modulus over 16384 bits")
	}
}
