// Intent Layer v2 W-B (intent_wb.go, rules 16-18) kill tests: targeted inputs whose expected results come from the TS
// reference (oracle-facts.ts, offer-set.ts, label-receipts.ts, param-provenance.ts, intent-classifier.ts,
// intent-env.ts), stored in testdata/killD_wb.json. Every case compares the FULL result (validator verdict, world /
// single_source, outcome / labels / classes / friction, ok / classes, activity, read purpose, W-B unit checks) with the
// reference, and pins this verifier's exact refusal reason (testdata/killD_wb_reasons.json; KILLD_UPDATE=1 rewrites it
// from the current build after a reviewed change; the expected results are generated by the flagship's
// tools/pca-audit/go-mutate/killD-oracle-gen.mjs). Boundaries are tested on both sides (n / n+1, 0 / -1, 64 / 65 ...).

type killDCase struct {
	Kind     string          `json:"kind"`
	Name     string          `json:"name"`
	Fn       string          `json:"fn"`
	Arg      json.RawMessage `json:"arg"`
	Want     json.RawMessage `json:"want"`
	WantOK   bool            `json:"want_ok"`
	A        float64         `json:"a"`
	B        float64         `json:"b"`
	Rules    json.RawMessage `json:"rules"`
	Cls      string          `json:"cls"`
	Origin   string          `json:"origin"`
	Aud      string          `json:"aud"`
	Input    json.RawMessage `json:"input"`
	Expect   json.RawMessage `json:"expect"`
	TSReason string          `json:"ts_reason"`
}

const killDGolden = "testdata/killD_wb.json"
const killDReasons = "testdata/killD_wb_reasons.json"

func killDParse(t *testing.T, raw json.RawMessage) any {
	t.Helper()
	if len(raw) == 0 {
		return nil
	}
	v, err := ParseJSONLenient(raw)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	return normalizeJSON(v)
}

var killDValidators = map[string]func(any) bool{
	"validateFactWire":              validateFactWire,
	"validateWorldPolicy":           validateWorldPolicy,
	"validateOfferPolicy":           validateOfferPolicy,
	"validateOfferSetWire":          validateOfferSetWire,
	"validateLabelsWire":            validateLabelsWire,
	"validateFlowRules":             validateFlowRules,
	"validateProvenancePolicy":      validateProvenancePolicy,
	"validateProvWire":              validateProvWire,
	"validateClassifierVerdictWire": validateClassifierVerdictWire,
	"validateClassifierPolicy":      validateClassifierPolicy,
}

// killDRun evaluates one case; it returns the comparable result and this verifier's reason ("" when none).
func killDRun(t *testing.T, c killDCase) (any, string) {
	t.Helper()
	switch c.Kind {
	case "fn":
		f, ok := killDValidators[c.Fn]
		if !ok {
			t.Fatalf("unknown validator %s", c.Fn)
		}
		return f(killDParse(t, c.Arg)), ""
	case "ratio":
		v, ok := ratioPpm(c.A, c.B)
		return map[string]any{"ok": ok, "v": jsNumber(v)}, ""
	case "flowRule":
		rules, _ := killDParse(t, c.Rules).(map[string]any)
		p, ok := flowRuleFor(rules, c.Cls)
		return map[string]any{"ok": ok, "p": p}, ""
	case "flowAllowed":
		rules, _ := killDParse(t, c.Rules).(map[string]any)
		return flowAllowed(rules, c.Cls, c.Origin, c.Aud), ""
	case "world":
		return IntentWorldPrimitive(killDParse(t, c.Input))
	case "prov":
		return IntentProvenancePrimitive(killDParse(t, c.Input))
	case "cls":
		return IntentClassifierPrimitive(killDParse(t, c.Input))
	case "active":
		return IntentWBActivePrimitive(killDParse(t, c.Input)), ""
	case "read":
		return IntentReadPurposePrimitive(killDParse(t, c.Input)), ""
	case "wb":
		in := killDParse(t, c.Input).(map[string]any)
		action, _ := in["action"].(map[string]any)
		is, _ := in["intent_session"].(map[string]any)
		r := decideIntentWB(jsF(in["now"]), in["aud"].(string), in["session"].(string), action, is, in["artifacts"], in["policy"])
		checks := map[string]any{}
		for k, v := range r.checks {
			checks[k] = v
		}
		return map[string]any{"outcome": r.outcome, "checks": checks}, r.reason
	}
	t.Fatalf("unknown kind %s", c.Kind)
	return nil, ""
}

// killDExpected is the reference result in the shape killDRun returns.
func killDExpected(t *testing.T, c killDCase) any {
	switch c.Kind {
	case "fn":
		return killDParse(t, c.Want)
	case "ratio":
		var w float64
		if err := json.Unmarshal(c.Want, &w); err != nil {
			t.Fatal(err)
		}
		return map[string]any{"ok": c.WantOK, "v": jsNumber(w)}
	case "flowRule":
		return map[string]any{"ok": c.WantOK, "p": killDParse(t, c.Want)}
	case "flowAllowed":
		return killDParse(t, c.Want)
	}
	return killDParse(t, c.Expect)
}

func TestKillDIntentWBOracle(t *testing.T) {
	b, err := os.ReadFile(killDGolden)
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Cases []killDCase `json:"cases"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		t.Fatal(err)
	}
	if len(doc.Cases) < 1000 {
		t.Fatalf("only %d oracle cases", len(doc.Cases))
	}
	reasons := map[string]string{}
	update := os.Getenv("KILLD_UPDATE") == "1"
	if !update {
		rb, err := os.ReadFile(killDReasons)
		if err != nil {
			t.Fatal(err)
		}
		if err := json.Unmarshal(rb, &reasons); err != nil {
			t.Fatal(err)
		}
	}
	got := map[string]string{}
	for _, c := range doc.Cases {
		res, reason := killDRun(t, c)
		want := killDExpected(t, c)
		if !sameJSON(res, want) {
			gj, _ := json.Marshal(res)
			wj, _ := json.Marshal(want)
			t.Errorf("%s: got %s, reference %s (reference reason %q, ours %q)", c.Name, gj, wj, c.TSReason, reason)
		}
		// a refusal reason is reported iff the reference reports one (prefix family agrees: facts / provenance / classes)
		decides := c.Kind == "world" || c.Kind == "prov" || c.Kind == "cls" || c.Kind == "wb"
		if decides && (reason == "") != (c.TSReason == "") {
			t.Errorf("%s: reason %q, reference reason %q", c.Name, reason, c.TSReason)
		}
		if decides && reason != "" && c.TSReason != "" && killDFamily(reason) != killDFamily(c.TSReason) {
			t.Errorf("%s: reason family %q, reference %q", c.Name, reason, c.TSReason)
		}
		got[c.Name] = reason
		if !update && reasons[c.Name] != reason {
			t.Errorf("%s: reason %q, pinned %q", c.Name, reason, reasons[c.Name])
		}
	}
	if update {
		keys := make([]string, 0, len(got))
		for k := range got {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		out, _ := json.MarshalIndent(got, "", " ")
		if err := os.WriteFile(killDReasons, append(out, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("rewrote %s (%d reasons)", killDReasons, len(keys))
	}
}

func killDFamily(r string) string {
	for i := 0; i < len(r); i++ {
		if r[i] == ':' {
			return r[:i]
		}
	}
	return r
}

// IntentSchemaPrimitive reports `digest` only when the schema signature verifies (README rule 14 primitive: {sig,
// digest? (when sig), conform}): every signed corpus schema checked against an EMPTY key set and against a key set
// that pins another public key must give sig false and no digest, with the same conform verdict.
func TestKillDIntentSchemaDigestOnlyWhenSigned(t *testing.T) {
	ran := 0
	for _, x := range v2Primitives(t, "intent_schema") {
		v := x.(map[string]any)
		if v["expect"].(map[string]any)["sig"] != true {
			continue
		}
		in := normalizeJSON(v["input"]).(map[string]any)
		good := IntentSchemaPrimitive(in)
		if good["sig"] != true || good["digest"] == nil {
			t.Fatalf("%s: signed schema not verified: %v", v["name"], good)
		}
		keys := in["keys"].([]any)
		other := map[string]any{}
		for k, val := range keys[0].(map[string]any) {
			other[k] = val
		}
		other["pk"] = "ngFoNxTzXeqGmwUazsE4YDMjft0mQAyAxRWdPwlU4YI"
		for _, ks := range []any{[]any{}, []any{other}} {
			bad := map[string]any{}
			for k, val := range in {
				bad[k] = val
			}
			bad["keys"] = ks
			out := IntentSchemaPrimitive(bad)
			if out["sig"] != false {
				t.Errorf("%s: sig %v under keys %v", v["name"], out["sig"], ks)
			}
			if _, has := out["digest"]; has {
				t.Errorf("%s: digest reported for an unverified schema", v["name"])
			}
			if !sameJSON(out["conform"], good["conform"]) {
				t.Errorf("%s: conform %v != %v", v["name"], out["conform"], good["conform"])
			}
		}
		ran++
	}
	if ran < 10 {
		t.Fatalf("only %d signed intent_schema vectors", ran)
	}
}
