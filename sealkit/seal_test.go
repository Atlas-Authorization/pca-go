type corpusCase struct {
	Name       string `json:"name"`
	EncInputs  string `json:"encInputs"`
	EncRiskRaw string `json:"encRiskRaw"`
	EncSlack   string `json:"encSlack"`
	Policy     struct {
		Scale              int64   `json:"scale"`
		Dim                int64   `json:"dim"`
		WeightsScaled      []int64 `json:"weightsScaled"`
		KappaWeightsScaled []int64 `json:"kappaWeightsScaled"`
		BudgetScaled       int64   `json:"budgetScaled"`
		Kappa              float64 `json:"kappa"`
	} `json:"policy"`
}

type corpus struct {
	Seal struct {
		PolyModulusDegree int   `json:"polyModulusDegree"`
		PlainModulus      int64 `json:"plainModulus"`
	} `json:"seal"`
	PublicKey  string       `json:"publicKey"`
	RelinKeys  string       `json:"relinKeys"`
	GaloisKeys string       `json:"galoisKeys"`
	Cases      []corpusCase `json:"cases"`
}

func loadCorpus(t *testing.T) *corpus {
	path := os.Getenv("PCA_FHE_SEAL_CORPUS")
	if path == "" {
		t.Fatal("PCA_FHE_SEAL_CORPUS must point at the node-seal corpus (generated by the oracle in CI)")
	}
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		t.Fatal(err)
	}
	var c corpus
	if err := json.NewDecoder(gz).Decode(&c); err != nil {
		t.Fatal(err)
	}
	return &c
}

func (c corpusCase) policy() *Policy {
	return &Policy{Scale: c.Policy.Scale, Dim: c.Policy.Dim, WeightsScaled: c.Policy.WeightsScaled, KappaWeightsScaled: c.Policy.KappaWeightsScaled, BudgetScaled: c.Policy.BudgetScaled, Kappa: c.Policy.Kappa}
}

// The evaluation is deterministic given (ciphertext, Galois keys, policy): the native result must equal the reference's byte for byte once
// both are re-saved uncompressed.
func TestEvaluatesTheReferenceCiphertextsToTheReferenceResults(t *testing.T) {
	c := loadCorpus(t)
	if c.Seal.PolyModulusDegree != PolyModulusDegree || c.Seal.PlainModulus != PlainModulus {
		t.Fatalf("corpus parameters differ from the native context: %+v", c.Seal)
	}
	if len(c.Cases) < 6 {
		t.Fatalf("expected at least 6 cases, got %d", len(c.Cases))
	}
	keys := &EvalKeys{PublicKey: c.PublicKey, RelinKeys: c.RelinKeys, GaloisKeys: c.GaloisKeys}
	for _, cs := range c.Cases {
		gate, err := EvalRiskGate(keys, cs.EncInputs, cs.policy())
		if err != nil {
			t.Fatalf("%s: %v", cs.Name, err)
		}
		for _, p := range [][2]string{{cs.EncRiskRaw, gate.EncRiskRaw}, {cs.EncSlack, gate.EncSlack}} {
			want, err1 := CanonicalCipher(p[0])
			got, err2 := CanonicalCipher(p[1])
			if err1 != nil || err2 != nil {
				t.Fatalf("%s: canonical: %v %v", cs.Name, err1, err2)
			}
			if want != got {
				t.Errorf("%s: evaluated ciphertext differs from the reference", cs.Name)
			}
		}
	}
}

func makePolicy(kappa, budget float64) *Policy {
	w := []float64{0.25, 0.2, 0.2, 0.2, 0.1, 0.05}
	p := &Policy{Scale: 1000, Dim: 6, BudgetScaled: int64(budget*1e6 + 0.5), Kappa: kappa}
	for _, v := range w {
		p.WeightsScaled = append(p.WeightsScaled, int64(v*1000+0.5))
		p.KappaWeightsScaled = append(p.KappaWeightsScaled, int64(kappa*v*1000+0.5))
	}
	return p
}

func TestNativeRoundTripMatchesPlaintextArithmetic(t *testing.T) {
	keys, err := Keygen()
	if err != nil {
		t.Fatal(err)
	}
	ek := &EvalKeys{PublicKey: keys.PublicKey, RelinKeys: keys.RelinKeys, GaloisKeys: keys.GaloisKeys}
	for _, tc := range []struct {
		x             []int64
		kappa, budget float64
	}{{[]int64{100, 900, 100, 100, 100, 100}, 1, 0.6}, {[]int64{1000, 1000, 1000, 1000, 1000, 1000}, 1, 0.5}, {[]int64{0, 0, 0, 0, 0, 0}, 1.5, 0.25}} {
		p := makePolicy(tc.kappa, tc.budget)
		enc, err := EncryptRiskInputs(keys.PublicKey, tc.x)
		if err != nil {
			t.Fatal(err)
		}
		gate, err := EvalRiskGate(ek, enc, p)
		if err != nil {
			t.Fatal(err)
		}
		v, err := DecryptVerdict(keys.SecretKey, gate.EncRiskRaw, gate.EncSlack, p)
		if err != nil {
			t.Fatal(err)
		}
		var raw, kr int64
		for i := range tc.x {
			raw += p.WeightsScaled[i] * tc.x[i]
			kr += p.KappaWeightsScaled[i] * tc.x[i]
		}
		if v.RScaled != raw || v.Slack != p.BudgetScaled-kr || v.Admit != (v.Slack >= 0) {
			t.Errorf("verdict %+v, want r=%d slack=%d", v, raw, p.BudgetScaled-kr)
		}
	}
}

func TestAllZeroWeightsEvaluateToZero(t *testing.T) {
	keys, err := Keygen()
	if err != nil {
		t.Fatal(err)
	}
	p := &Policy{Scale: 1000, Dim: 6, WeightsScaled: make([]int64, 6), KappaWeightsScaled: make([]int64, 6), BudgetScaled: 5000, Kappa: 1}
	enc, _ := EncryptRiskInputs(keys.PublicKey, []int64{5, 5, 5, 5, 5, 5})
	gate, err := EvalRiskGate(&EvalKeys{PublicKey: keys.PublicKey, RelinKeys: keys.RelinKeys, GaloisKeys: keys.GaloisKeys}, enc, p)
	if err != nil {
		t.Fatal(err)
	}
	v, err := DecryptVerdict(keys.SecretKey, gate.EncRiskRaw, gate.EncSlack, p)
	if err != nil || v.RScaled != 0 || v.Slack != 5000 || !v.Admit {
		t.Fatalf("verdict %+v err %v", v, err)
	}
}

func TestWrongKeyFailsClosed(t *testing.T) {
	a, err := Keygen()
	if err != nil {
		t.Fatal(err)
	}
	b, err := Keygen()
	if err != nil {
		t.Fatal(err)
	}
	p := makePolicy(1, 0.6)
	enc, _ := EncryptRiskInputs(a.PublicKey, []int64{1, 2, 3, 4, 5, 6})
	gate, err := EvalRiskGate(&EvalKeys{PublicKey: a.PublicKey, RelinKeys: a.RelinKeys, GaloisKeys: a.GaloisKeys}, enc, p)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := DecryptVerdict(b.SecretKey, gate.EncRiskRaw, gate.EncSlack, p); err == nil || !strings.Contains(err.Error(), "noise budget") {
		t.Fatalf("expected a noise-budget refusal, got %v", err)
	}
}

func TestMalformedBlobsAndPoliciesAreRefused(t *testing.T) {
	keys, err := Keygen()
	if err != nil {
		t.Fatal(err)
	}
	good, _ := EncryptRiskInputs(keys.PublicKey, []int64{1, 2, 3, 4, 5, 6})
	for name, blob := range map[string]string{"truncated": good[:len(good)-8], "padded": good + "AAAA", "short": "AAAA", "zeros": strings.Repeat("A", 64)} {
		if _, err := AssertSealBlob(blob, name); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
	bad := []*Policy{
		{Scale: 1000, Dim: 5, WeightsScaled: make([]int64, 6), KappaWeightsScaled: make([]int64, 6)},
		{Scale: 1000, Dim: 6, WeightsScaled: make([]int64, 6), KappaWeightsScaled: make([]int64, 6), BudgetScaled: SignedBound},
		{Scale: 0, Dim: 6, WeightsScaled: make([]int64, 6), KappaWeightsScaled: make([]int64, 6)},
		{Scale: 1000, Dim: 6, WeightsScaled: make([]int64, 5), KappaWeightsScaled: make([]int64, 6)},
		nil,
	}
	for i, p := range bad {
		if RequirePolicy(p) == nil {
			t.Errorf("policy %d accepted", i)
		}
	}
	if _, err := EncryptRiskInputs("x", []int64{-1, 0, 0, 0, 0, 0}); err == nil {
		t.Error("negative input accepted")
	}
}
